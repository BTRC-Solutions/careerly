import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { findVendoredTypst } from '../platform/config/typst-binary.js';

/** Creates an isolated temporary folder for an integration test. Call `cleanup()` in `afterEach`. */
export function createTempDir(prefix = 'careerly-test-') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  return {
    dir,
    cleanup: () => fs.rmSync(dir, { recursive: true, force: true }),
  };
}

/** The built-in CV templates. */
export const TEMPLATES_DIR = path.resolve(import.meta.dirname, '..', '..', 'templates');

/** The Typst CLI for tests: `TYPST_BIN`, else the vendored one (`npm run typst:fetch`), else the PATH's. */
export const TEST_TYPST_BINARY =
  process.env.TYPST_BIN ??
  findVendoredTypst(path.resolve(import.meta.dirname, '..', '..', '..', '..')) ??
  'typst';

/** Whether {@link TEST_TYPST_BINARY} runs; render tests are skipped without it (CI always has it). */
export const HAS_TYPST = spawnSync(TEST_TYPST_BINARY, ['--version']).status === 0;

/** The real migrations generated by drizzle-kit. */
export const MIGRATIONS_DIR = path.resolve(import.meta.dirname, '..', '..', 'drizzle');

/** Tags of the real migrations, in order (read from the drizzle-kit journal). */
export const MIGRATION_TAGS: string[] = (
  JSON.parse(fs.readFileSync(path.join(MIGRATIONS_DIR, 'meta', '_journal.json'), 'utf8')) as {
    entries: { idx: number; tag: string }[];
  }
).entries
  .sort((a, b) => a.idx - b.idx)
  .map((entry) => entry.tag);

import fs from 'node:fs';
import path from 'node:path';
import type { DatabaseSync } from 'node:sqlite';
import { z } from 'zod';
import { inTransaction, openDatabase } from './sqlite.js';

const MIGRATIONS_TABLE = '__careerly_migrations';
const STATEMENT_BREAKPOINT = '--> statement-breakpoint';
const BACKUPS_TO_KEEP = 10;

/** Subset of the journal that `drizzle-kit generate` writes to `<migrationsDir>/meta/_journal.json`. */
const JournalSchema = z.object({
  entries: z.array(z.object({ idx: z.number(), tag: z.string() })),
});

export interface MigrationOptions {
  databaseFile: string;
  migrationsDir: string;
  backupsDir: string;
  /** Injectable clock, for deterministic backup names in tests. */
  now?: () => Date;
}

export interface MigrationResult {
  applied: string[];
  totalApplied: number;
  backupFile: string | undefined;
}

export class MigrationError extends Error {
  constructor(
    readonly tag: string,
    readonly backupFile: string | undefined,
    cause: unknown,
  ) {
    super(
      `Migration "${tag}" failed${backupFile ? '; the database was restored from the backup' : ''}.`,
      {
        cause,
      },
    );
    this.name = 'MigrationError';
  }
}

/**
 * Applies pending migrations generated by drizzle-kit (RNF-20):
 * 1. If the database already has data, writes a backup first (`VACUUM INTO`).
 * 2. Applies all pending migrations in a single transaction.
 * 3. If anything fails, rolls back and restores the backup file, then throws {@link MigrationError}.
 */
export function migrateDatabase(options: MigrationOptions): MigrationResult {
  const pending = readJournal(options.migrationsDir);
  let db = openDatabase(options.databaseFile);
  let backupFile: string | undefined;
  let currentTag = '(setup)';

  try {
    db.exec(
      `CREATE TABLE IF NOT EXISTS ${MIGRATIONS_TABLE} (tag TEXT PRIMARY KEY NOT NULL, applied_at TEXT NOT NULL);`,
    );
    const applied = new Set(
      db
        .prepare(`SELECT tag FROM ${MIGRATIONS_TABLE}`)
        .all()
        .map((row) => String(row.tag)),
    );
    const toApply = pending.filter((entry) => !applied.has(entry.tag));

    if (toApply.length === 0) {
      return { applied: [], totalApplied: applied.size, backupFile: undefined };
    }

    if (applied.size > 0) {
      backupFile = backupDatabase(db, options);
    }

    inTransaction(db, () => {
      const record = db.prepare(`INSERT INTO ${MIGRATIONS_TABLE} (tag, applied_at) VALUES (?, ?)`);
      for (const entry of toApply) {
        currentTag = entry.tag;
        for (const statement of readStatements(options.migrationsDir, entry.tag)) {
          db.exec(statement);
        }
        record.run(entry.tag, (options.now?.() ?? new Date()).toISOString());
      }
    });

    return {
      applied: toApply.map((entry) => entry.tag),
      totalApplied: applied.size + toApply.length,
      backupFile,
    };
  } catch (error) {
    if (backupFile) {
      db.close();
      restoreBackup(backupFile, options.databaseFile);
      db = openDatabase(options.databaseFile);
    }
    throw new MigrationError(currentTag, backupFile, error);
  } finally {
    db.close();
  }
}

/** Number of migrations already applied (0 for a database that was never migrated). */
export function countAppliedMigrations(db: DatabaseSync): number {
  const exists = db
    .prepare(`SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?`)
    .get(MIGRATIONS_TABLE);
  if (!exists) {
    return 0;
  }
  const row = db.prepare(`SELECT COUNT(*) AS count FROM ${MIGRATIONS_TABLE}`).get();
  return Number(row?.count ?? 0);
}

function readJournal(migrationsDir: string) {
  const journalPath = path.join(migrationsDir, 'meta', '_journal.json');
  const journal = JournalSchema.parse(JSON.parse(fs.readFileSync(journalPath, 'utf8')));
  return [...journal.entries].sort((a, b) => a.idx - b.idx);
}

function readStatements(migrationsDir: string, tag: string): string[] {
  const sql = fs.readFileSync(path.join(migrationsDir, `${tag}.sql`), 'utf8');
  return sql
    .split(STATEMENT_BREAKPOINT)
    .map((statement) => statement.trim())
    .filter(Boolean);
}

function backupDatabase(db: DatabaseSync, options: MigrationOptions): string {
  fs.mkdirSync(options.backupsDir, { recursive: true });
  const stamp = (options.now?.() ?? new Date()).toISOString().replace(/[:.]/g, '-');
  const backupFile = path.join(options.backupsDir, `careerly-${stamp}-pre-migration.db`);
  db.prepare('VACUUM INTO ?').run(backupFile);
  pruneBackups(options.backupsDir);
  return backupFile;
}

function restoreBackup(backupFile: string, databaseFile: string) {
  for (const suffix of ['-wal', '-shm']) {
    fs.rmSync(`${databaseFile}${suffix}`, { force: true });
  }
  fs.copyFileSync(backupFile, databaseFile);
}

function pruneBackups(backupsDir: string) {
  const backups = fs
    .readdirSync(backupsDir)
    .filter((name) => name.endsWith('-pre-migration.db'))
    .sort();
  for (const name of backups.slice(0, Math.max(0, backups.length - BACKUPS_TO_KEEP))) {
    fs.rmSync(path.join(backupsDir, name), { force: true });
  }
}
